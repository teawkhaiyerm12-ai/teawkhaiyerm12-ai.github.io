def fig(name, pins=(), kind="tablet", legend=True):
    """ภาพหน้าจอพร้อมหมุดตัวเลข  pins = [(x_px, y_px, "คำอธิบาย"), ...] ตามพิกเซลของรูปจริง
    วางหมุดไว้ข้าง ๆ ปุ่ม ไม่ใช่ทับตัวปุ่ม คนอ่านจะได้เห็นข้อความบนปุ่ม"""
    from PIL import Image
    w, h = Image.open(IMG / f"{name}.jpg").size
    dots = "".join(f'<span class="pin" style="left:{x / w * 100:.2f}%;top:{y / h * 100:.2f}%">{i}</span>'
                   for i, (x, y, _) in enumerate(pins, 1))
    leg = ""
    if pins and legend:
        leg = '<ul class="legend">' + "".join(
            f'<li><b class="n">{i}</b><span>{t}</span></li>' for i, (_, _, t) in enumerate(pins, 1)) + "</ul>"
    return (f'<div class="fig"><div class="shot {kind}"><img src="../../docs/manual-img/{name}.jpg">{dots}</div>'
            f'{leg}</div>')


